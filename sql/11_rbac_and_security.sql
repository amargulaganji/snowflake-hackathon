-- 1G. USER-MEMBER ACCESS MAPPING TABLE
-- =============================================================================

CREATE OR REPLACE TABLE CLINICAL_COPILOT.CORE.USER_MEMBER_ACCESS (
    SNOWFLAKE_USER  VARCHAR NOT NULL,
    MEMBER_ID       VARCHAR NOT NULL,
    ACCESS_LEVEL    VARCHAR DEFAULT 'read',
    ASSIGNED_AT     TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    PRIMARY KEY (SNOWFLAKE_USER, MEMBER_ID)
);

-- Seed AMARGULAGANJI with access to all 50 members
INSERT INTO CLINICAL_COPILOT.CORE.USER_MEMBER_ACCESS (SNOWFLAKE_USER, MEMBER_ID)
