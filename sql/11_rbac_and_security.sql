FROM CLINICAL_COPILOT.CORE.MEMBER;

-- =============================================================================
-- 1H. ROW ACCESS POLICY ON MEMBER_ID
-- =============================================================================

CREATE OR REPLACE ROW ACCESS POLICY MEMBER_ACCESS_POLICY
  AS (member_id_val VARCHAR) RETURNS BOOLEAN ->
    IS_ROLE_IN_SESSION('SNOWCARE_ADMIN_ROLE')
    OR IS_ROLE_IN_SESSION('ACCOUNTADMIN')
    OR EXISTS (
      SELECT 1 FROM CLINICAL_COPILOT.CORE.USER_MEMBER_ACCESS
      WHERE SNOWFLAKE_USER = CURRENT_USER()
        AND MEMBER_ID = member_id_val
    );

-- Apply to all tables with MEMBER_ID
ALTER TABLE MEMBER              ADD ROW ACCESS POLICY MEMBER_ACCESS_POLICY ON (MEMBER_ID);
