-- 1I. MASKING POLICIES
-- =============================================================================

-- PCP_NAME masking
CREATE OR REPLACE MASKING POLICY PCP_NAME_MASK AS (val VARCHAR) RETURNS VARCHAR ->
  CASE
    WHEN IS_ROLE_IN_SESSION('CARE_MANAGER_ROLE')       THEN val
    WHEN IS_ROLE_IN_SESSION('COMPLIANCE_ANALYST_ROLE')  THEN val
    WHEN IS_ROLE_IN_SESSION('SNOWCARE_ADMIN_ROLE')      THEN val
    WHEN IS_ROLE_IN_SESSION('ACCOUNTADMIN')              THEN val
    ELSE '***REDACTED***'
  END;

ALTER TABLE MEMBER MODIFY COLUMN PCP_NAME SET MASKING POLICY PCP_NAME_MASK;

-- DOB masking (MEMBER.DOB exists as DATE)
CREATE OR REPLACE MASKING POLICY DOB_MASK AS (val DATE) RETURNS DATE ->
  CASE
    WHEN IS_ROLE_IN_SESSION('CARE_MANAGER_ROLE')       THEN val
    WHEN IS_ROLE_IN_SESSION('COMPLIANCE_ANALYST_ROLE')  THEN val
    WHEN IS_ROLE_IN_SESSION('SNOWCARE_ADMIN_ROLE')      THEN val
    WHEN IS_ROLE_IN_SESSION('ACCOUNTADMIN')              THEN val
    ELSE DATE_FROM_PARTS(YEAR(val), 1, 1)  -- mask to Jan 1 of birth year
  END;

ALTER TABLE MEMBER MODIFY COLUMN DOB SET MASKING POLICY DOB_MASK;

